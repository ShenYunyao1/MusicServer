const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const net = require('node:net');
const { spawn, spawnSync } = require('node:child_process');
const { chromium } = require(process.env.MUSIC_SERVER_PLAYWRIGHT || 'playwright');

async function main() {
  const binary = process.env.MUSIC_SERVER_TEST_BINARY;
  assert.ok(binary, 'Set MUSIC_SERVER_TEST_BINARY to a built server executable');
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'musicserver-ui-v09-'));
  const password = 'isolated administrator password';
  const database = path.join(directory, 'library.sqlite');
  const initialize = spawnSync(process.env.MUSIC_SERVER_TEST_PYTHON || 'python', [path.join(__dirname, 'admin-terminal.py'), binary, database, 'admin'], { input: password + '\n', encoding: 'utf8', timeout: 30000, windowsHide: true });
  assert.equal(initialize.status, 0, initialize.stdout + initialize.stderr);
  const media = path.join(directory, 'media');
  await fs.mkdir(media);
  const audio = Buffer.alloc(844);
  audio.write('RIFF');
  audio.writeUInt32LE(audio.length - 8, 4);
  audio.write('WAVEfmt ', 8);
  audio.writeUInt32LE(16, 16);
  audio.writeUInt16LE(1, 20);
  audio.writeUInt16LE(1, 22);
  audio.writeUInt32LE(8000, 24);
  audio.writeUInt32LE(16000, 28);
  audio.writeUInt16LE(2, 32);
  audio.writeUInt16LE(16, 34);
  audio.write('data', 36);
  audio.writeUInt32LE(800, 40);
  await fs.writeFile(path.join(media, 'First.wav'), audio);
  const listener = net.createServer();
  await new Promise(resolve => listener.listen(0, '127.0.0.1', resolve));
  const port = listener.address().port;
  await new Promise(resolve => listener.close(resolve));
  const lanIP = process.env.MUSIC_SERVER_UI_LAN_IP;
  const base = 'http://' + (lanIP || '127.0.0.1') + ':' + port;
  const server = spawn(binary, ['-addr', (lanIP ? '0.0.0.0' : '127.0.0.1') + ':' + port, '-media-root', media, '-data', database], { windowsHide: true });
  let serverLog = '';
  server.stderr.on('data', data => { serverLog += data; });
  let browser;
  try {
    let ready = false;
    for (let attempt = 0; attempt < 100; attempt++) {
      try {
        const response = await fetch(base + '/api/v2/health');
        if (response.ok) { ready = true; break; }
      } catch {}
      await new Promise(resolve => setTimeout(resolve, 100));
    }
    assert.ok(ready, serverLog);
    browser = await chromium.launch({ headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
    const pageErrors = [];
    page.on('pageerror', error => {pageErrors.push(error.message);console.error('Browser error: '+error.stack)});
    await page.goto(base);
    if (lanIP) {
      assert.equal(await page.evaluate(() => isSecureContext), false, 'LAN regression must use an actual HTTP insecure context');
      assert.equal(await page.evaluate(() => typeof crypto.randomUUID), 'undefined');
      assert.equal(await page.evaluate(() => typeof navigator.clipboard), 'undefined');
    }
    await page.locator('#username').waitFor();
    await page.screenshot({ path: path.join(directory, 'login.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Login should fit mobile width');
    await page.screenshot({ path: path.join(directory, 'login-mobile.png'), fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1100 });
    await page.fill('#username', 'admin');
    await page.fill('#password', password);
    await page.click('#loginButton');
    await page.waitForFunction(() => state.tracks.length === 1);
    await page.reload();
    await page.waitForFunction(() => state.user?.username === 'admin' && state.tracks.length === 1);
    await page.waitForFunction(() => document.querySelector('#status').textContent === '已登录');
    await require('./navigation-ui.cjs')({page});
    await page.screenshot({ path: path.join(directory, 'management.png'), fullPage: true });
    await page.evaluate(() => editTrack(state.tracks[0]));
    await page.fill('[data-field="title"]', 'Edited in browser');
    await page.click('#saveModal');
    await page.waitForFunction(() => state.tracks[0].title === 'Edited in browser');
    await page.click('[data-page="playlists"]');
    await page.click('#newPlaylist');
    await page.fill('[data-field="name"]', 'Browser playlist');
    await page.click('#saveModal');
    await page.waitForFunction(() => state.playlists.some(playlist => playlist.name === 'Browser playlist') ||
      document.querySelector('#status').textContent.includes('randomUUID'));
    assert.ok(await page.evaluate(() => state.playlists.some(playlist => playlist.name === 'Browser playlist')),
      await page.locator('#status').textContent());
    const createdPlaylistID = await page.evaluate(() => state.playlists.find(p => p.name === 'Browser playlist').id);
    assert.match(createdPlaylistID, /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/);
    await page.evaluate(id=>location.hash='#/playlists/'+id,createdPlaylistID);
    await page.waitForFunction(id=>state.playlistDetailId===id,createdPlaylistID);
    await page.reload();await page.waitForFunction(id=>state.playlistDetailId===id&&document.querySelector('#status').textContent==='已登录',createdPlaylistID);
    assert.equal(await page.locator('#playlistDetail').isVisible(),true);
    await page.click('[data-back-playlists]');await page.waitForFunction(()=>state.playlistDetailId===null);
    await page.evaluate(async () => { await reorder(state.playlists.find(playlist => playlist.name === 'Browser playlist').id, 'library'); });
    await page.evaluate(() => openPlaylistTrackPicker(state.playlists.find(playlist => playlist.name === 'Browser playlist')));
    await page.locator('#modalBody input[type="checkbox"]').check();
    await page.click('#saveModal');
    await page.waitForFunction(() => state.playlists.find(playlist => playlist.name === 'Browser playlist').track_ids.length === 1);
    await page.evaluate(() => editPlaylistTrackNote(state.playlists.find(playlist => playlist.name === 'Browser playlist'), state.tracks[0]));
    await page.fill('[data-field="comment"]', 'Browser cue');
    await page.click('#saveModal');
    await page.waitForFunction(() => state.playlists.find(playlist => playlist.name === 'Browser playlist').track_notes?.[state.tracks[0].id] === 'Browser cue');
    await require('./music-layout-ui.cjs')({page,directory});
    await page.evaluate(() => editTrack(state.tracks[0]));
    await page.evaluate(async () => { await api('tracks/' + state.tracks[0].id, 'PATCH', { comment: 'Concurrent edit' }, undefined, state.tracks[0].version); });
    await page.fill('[data-field="title"]', 'Stale edit');
    await page.click('#saveModal');
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('409'));
    assert.equal(await page.locator('#editorError').isVisible(),true);
    assert.equal(await page.locator('[data-field="title"]').inputValue(),'Stale edit');
    await page.click('#cancelModal');
    await page.evaluate(() => refreshCore());
    await page.click('[data-page="maintenance"]');
    await page.evaluate(async () => { const track = state.tracks[0]; await api('tracks/' + track.id, 'DELETE', undefined, undefined, track.version); await refreshCore(); });
    await page.locator('#maintenanceTabs a[href="#/admin/library/removed"]').click();await page.locator('#viewRemoved').click();
    await page.locator('#removedResults button').click();
    await page.waitForFunction(() => state.tracks.length === 1);
    assert.equal(await page.evaluate(() => state.playlists.find(playlist => playlist.name === 'Browser playlist').track_notes[state.tracks[0].id]), 'Browser cue');
    await page.click('[data-page="settings"]');await page.locator('#settingsTabs a[href="#/admin/settings/backup"]').click();await page.click('#createBackup');
    await page.waitForFunction(() => document.querySelector('#backupResult').textContent.includes('.sqlite'));
    await page.locator('#settingsTabs a[href="#/admin/settings/audit"]').click();await page.click('#viewAudit');
    await page.waitForFunction(() => document.querySelectorAll('#auditResults details').length > 0);
    await page.click('[data-page="maintenance"]');await page.click('#scan');
    await page.waitForFunction(() => document.querySelector('#scanProgress').dataset.state==='completed');
    await page.click('#fullScan');
    await page.waitForFunction(async () => (await api('admin/scan/status')).state === 'completed');
    await page.click('[data-page="keys"]');
    await page.click('#newKey');
    await page.fill('#policyName', 'Browser player');
    await page.fill('#policyConcurrency', '3');
    await page.fill('#policyDownloads', '2');
    await page.click('#saveModal');
    await page.waitForFunction(() => document.querySelector('#secretDialog').open);
    const playerSecret = await page.locator('#secretValue').textContent();
    assert.ok(playerSecret);
    const zeroStats = await page.evaluate(() => api('admin/stats'));
    assert.equal(zeroStats.keys.length, 1);
    assert.equal(zeroStats.keys[0].key_name, 'Browser player');
    assert.equal(zeroStats.total.total_requests, 0, 'Creating a key and browser management calls must not count as player calls');
    const keyCheck = await page.evaluate(async secret => {
      const response = await fetch('/api/v2/admin/settings', { headers: { 'X-API-Key': secret } });
      return response.status;
    }, playerSecret);
    assert.equal(keyCheck, 403, 'Player key must not inherit the browser administrator session');
    await page.click('#doneSecret');
    assert.ok((await page.locator('#secretValue').textContent())==='','One-time key must clear when the dialog closes');
    await page.click('[data-page="stats"]');
    await page.waitForFunction(() => state.stats?.total.total_requests === 1);
    assert.equal(await page.locator('#statsTable tbody tr').count(), 1);
    assert.ok((await page.locator('#statsTable').textContent()).includes('Browser player'));
    await page.click('[data-page="keys"]');
    await page.locator('[data-edit-key]').click();
    await page.fill('#policyName', 'Browser renamed');
    await page.click('#saveModal');
    await page.waitForFunction(() => state.stats?.keys[0]?.key_name === 'Browser renamed');
    await page.click('[data-page="stats"]');
    await page.waitForFunction(() => document.querySelector('#statsTable').textContent.includes('Browser renamed'));
    await page.click('[data-page="keys"]');
    page.once('dialog', dialog => dialog.accept());
    await page.locator('[data-revoke-key]').click();
    await page.waitForFunction(() => state.stats?.keys.length === 0 && state.stats.total.total_requests === 0);
    await page.click('[data-page="stats"]');
    await page.waitForFunction(() => document.querySelector('#statsTable').textContent.includes('暂无 API Key 调用记录'));
    await page.click('[data-page="upload"]');
    audio[44] = 1;
    await page.setInputFiles('#uploadInput', { name: 'Upload.wav', mimeType: 'audio/wav', buffer: audio });
    await page.waitForFunction(() => state.uploads.length === 1);
    assert.equal(await page.locator('.upload-editor').getAttribute('open'),null);
    await page.locator('.upload-editor > summary').click();await page.locator('[data-upload-field="title"]').waitFor({state:'visible'});
    await page.locator('.upload-editor > summary').click();
    await page.locator('[data-stage-upload]').click();
    await page.waitForFunction(() => state.uploads[0].stageId);
    await page.locator('[data-confirm-upload]').click();
    await page.waitForFunction(() => state.tracks.length === 2);
    await page.click('[data-page="tracks"]');await page.waitForFunction(()=>state.page==='tracks');await page.locator('#selectAll').check();
    const batchIDs=await page.evaluate(()=>[...state.selectedTrackIds]);assert.equal(batchIDs.length,2);
    let batchConfirmations=0;const batchConfirm=dialog=>{batchConfirmations++;dialog.accept()};page.on('dialog',batchConfirm);
    await page.locator('#trackRows .row-actions button').filter({hasText:'更多'}).first().click();await page.locator('#contextMenu').getByText('下架曲目',{exact:true}).click();
    await page.waitForFunction(()=>state.tracks.length===0);page.off('dialog',batchConfirm);assert.equal(batchConfirmations,1,'Batch removal should confirm its count once');
    await page.evaluate(async ids=>{for(const track of await api('admin/removed'))if(ids.includes(track.id))await api('admin/removed/'+track.id,'POST',undefined,undefined,track.version);await refreshCore()},batchIDs);
    assert.equal(await page.evaluate(()=>state.tracks.length),2);
    const otherContext = await browser.newContext();
    const otherPage = await otherContext.newPage();
    await otherPage.goto(base);
    await otherPage.fill('#username', 'admin');
    await otherPage.fill('#password', password);
    await otherPage.click('#loginButton');
    await otherPage.waitForFunction(() => state.user?.username === 'admin');
    await page.locator('#accountMenu summary').click();
    await page.click('#manageSessions');
    await page.locator('#modalBody button').filter({ hasText: '撤销' }).click();
    await page.locator('#modalBody button').filter({ hasText: '撤销' }).waitFor({ state: 'detached' });
    assert.equal(await otherPage.evaluate(async () => (await fetch('/api/v2/auth/me')).status), 401);
    await page.click('#cancelModal');
    await otherContext.close();
    await page.locator('#accountMenu summary').click();
    await page.click('#changePassword');
    await page.fill('[data-field="old_password"]', password);
    await page.fill('[data-field="new_password"]', 'changed administrator password');
    await page.fill('[data-field="confirm_password"]', 'changed administrator password');
    await page.click('#saveModal');
    await page.waitForFunction(() => !state.user && !document.querySelector('#loginScreen').hidden);
    await page.fill('#username', 'admin');
    await page.fill('#password', password);
    await page.click('#loginButton');
    await page.waitForFunction(() => document.querySelector('#loginError').textContent.includes('401'));
    await page.fill('#password', 'changed administrator password');
    await page.click('#loginButton');
    await page.waitForFunction(() => state.user?.username === 'admin');
    const members=await require('./multiuser-ui.cjs')({browser,adminPage:page,base,audio,directory});
    await require('./users-ui.cjs')({browser,page,base,directory,...members});
    await require('./admin-layout-ui.cjs')({page,directory,...members});
    await page.locator('#accountMenu summary').click();
    await page.click('#logout');
    await page.waitForFunction(() => !state.user);
    assert.equal(await page.evaluate(()=>state.auditEntries.length),0);
    assert.equal(await page.locator('#secretValue').textContent(),'');
    assert.equal(await page.locator('#trackDetailsBody').textContent(),'');
    assert.equal(await page.evaluate(async () => (await fetch('/api/v2/auth/me')).status), 401);
    assert.deepEqual(pageErrors, []);
    console.log('Management UI passed: hidden console bootstrap, account login/reload/logout, session revocation, password change, key isolation, editing, playlists, restore, backup, audit, scanning and upload.');
    console.log('Isolated test data: ' + directory);
  } finally {
    if (browser) await browser.close();
    server.kill();
    await new Promise(resolve => { if (server.exitCode !== null) resolve(); else server.once('exit', resolve); });
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
