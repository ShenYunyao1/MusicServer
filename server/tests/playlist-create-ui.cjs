const assert=require('node:assert/strict');
const path=require('node:path');

module.exports=async function({page,directory}){
  await page.click('[data-page="playlists"]');
  const before=await page.evaluate(()=>state.playlists.length);
  await page.click('#newPlaylist');await page.locator('#playlistEditForm').waitFor({state:'visible',timeout:5000});
  assert.equal(await page.evaluate(()=>location.hash),'#/playlists/new');
  assert.equal(await page.locator('#editor').isVisible(),false,'Creation must use the full editor, not the old modal');
  assert.equal(await page.locator('#playlistEditor h1').textContent(),'新建歌单');
  assert.equal(await page.locator('.playlist-danger-zone').count(),0);
  assert.equal(await page.inputValue('#playlistEditVisibility'),'private');
  await page.fill('#playlistEditName','Creation regression');await page.fill('#playlistEditDescription','Same editor for create and edit');
  await page.selectOption('#playlistEditVisibility','public');
  const image=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=160;c.height=100;c.getContext('2d').fillRect(0,0,160,100);return c.toDataURL('image/png').split(',')[1]});
  await page.setInputFiles('#playlistCoverFile',{name:'cover.png',mimeType:'image/png',buffer:Buffer.from(image,'base64')});
  await page.locator('#playlistCrop').waitFor({state:'visible'});await page.click('#applyPlaylistCrop');await page.locator('#playlistCrop').waitFor({state:'hidden'});
  assert.equal(await page.evaluate(async()=> (await api('playlists')).length),before,'Drafts and crop previews must not create records');
  const discardDismissed=page.waitForEvent('dialog').then(d=>d.dismiss());await page.click('#playlistEditBack');await discardDismissed;
  await page.waitForFunction(()=>playlistDraft&&location.hash===playlistDraft.route);
  assert.equal(await page.inputValue('#playlistEditName'),'Creation regression');
  // A failed save retains all metadata and the local artwork for a retry.
  await page.route('**/api/v2/playlists',route=>route.request().method()==='POST'?route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:{message:'creation retry fixture'}})}):route.continue());
  await page.click('#savePlaylistEdit');await page.locator('#playlistEditError').filter({hasText:'503'}).waitFor();
  assert.equal(await page.inputValue('#playlistEditDescription'),'Same editor for create and edit');
  assert.equal(await page.evaluate(()=>Boolean(playlistDraft.coverBlob)),true);
  assert.equal(await page.evaluate(async()=> (await api('playlists')).length),before);
  await page.unroute('**/api/v2/playlists');await page.click('#savePlaylistEdit');
  await page.waitForFunction(()=>!playlistDraft&&state.playlists.some(p=>p.name==='Creation regression'));
  const created=await page.evaluate(()=>state.playlists.find(p=>p.name==='Creation regression'));
  assert.equal(created.visibility,'public');assert.equal(created.version,1);assert.ok(created.cover_id);
  await page.locator('[data-edit-playlist]').click();await page.locator('#playlistEditName').waitFor();
  assert.equal(await page.inputValue('#playlistEditName'),created.name);
  assert.equal(await page.inputValue('#playlistEditVisibility'),'public');
  assert.equal(await page.locator('#playlistEditor h1').textContent(),'编辑歌单');
  await page.click('#cancelPlaylistEdit');await page.locator('[data-back-playlists]').click();
  await page.setViewportSize({width:390,height:844});
  await page.click('#newPlaylist');await page.locator('#playlistEditName').waitFor();
  await page.waitForFunction(()=>parseFloat(getComputedStyle(document.querySelector('.main')).marginLeft)===0);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:path.join(directory,'playlist-create-mobile.png'),fullPage:true,animations:'disabled'});
  await page.reload();await page.locator('#playlistEditName').waitFor();
  assert.equal(await page.inputValue('#playlistEditName'),'');
  await page.fill('#playlistEditName','Cancelled draft');page.once('dialog',d=>d.accept());await page.click('#cancelPlaylistEdit');
  await page.waitForFunction(()=>location.hash==='#/playlists'&&!playlistDraft);
  assert.equal(await page.evaluate(async()=> (await api('playlists')).length),before+1);
  await page.evaluate(async id=>{const p=state.playlists.find(p=>p.id===id);await api('playlists/'+id,'DELETE',undefined,undefined,p.version);await refreshCore()},created.id);
  await page.setViewportSize({width:1440,height:1100});
  await page.waitForFunction(()=>parseFloat(getComputedStyle(document.querySelector('.main')).marginLeft)>=231);
  console.log('Playlist creation passed: unified editor, private default, crop preview, atomic save, retained draft on failure, cancel/reload and mobile layout.');
};
